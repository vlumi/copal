// Render returns the system's blueprints as files by path: an index in
// README.md; programs/NAME, rules/NAME, copybooks/NAME and jobs/NAME as .md
// and .json; each program's flow as programs/NAME.svg and each job's
// network as jobs/NAME.svg. Links to the source are relative to dir, where
// the blueprints are to be written, so the source paths must be relative
// to the same working directory as dir.
func (s *System) Render(dir, title string) (map[string][]byte, error) {
	files := map[string][]byte{"README.md": []byte(s.indexMarkdown(dir, title))}
	if len(s.Datasets) > 0 {
		data, err := json.MarshalIndent(s.Datasets, "", "  ")
		if err != nil {
			return nil, err
		}
		files["datasets.json"] = append(data, '\n')
	}
	if len(s.Schedule) > 0 {
		data, err := json.MarshalIndent(s.Schedule, "", "  ")
		if err != nil {
			return nil, err
		}
		files["schedule.json"] = append(data, '\n')
	}
	if len(s.Entities) > 0 {
		data, err := json.MarshalIndent(s.Entities, "", "  ")
		if err != nil {
			return nil, err
		}
		files["entities.json"] = append(data, '\n')
	}
	for _, p := range s.Programs {
		if err := renderBoth(files, dir, "programs", p.Name, p, s.programMarkdown); err != nil {
			return nil, err
		}
		if len(p.Rules.Tables) > 0 {
			if err := renderBoth(files, dir, "rules", p.Name, p.Rules, rulesMarkdown); err != nil {
				return nil, err
			}
		}
		svg, err := flowDiagram(filepath.Join(dir, "programs"), p).SVG()
		if err != nil {
			return nil, fmt.Errorf("%s: %w", p.Name, err)
		}
		files[filepath.Join("programs", p.Name+".svg")] = svg
	}
	for _, c := range s.Copybooks {
		if err := renderBoth(files, dir, "copybooks", c.Name, c, copybookMarkdown); err != nil {
			return nil, err
		}
	}
	for _, job := range s.Jobs {
		if err := renderBoth(files, dir, "jobs", job.Name, job, jobMarkdown); err != nil {
			return nil, err
		}
		svg, err := jobDiagram(job).SVG()
		if err != nil {
			return nil, fmt.Errorf("%s: %w", job.Name, err)
		}
		files[filepath.Join("jobs", job.Name+".svg")] = svg
	}
	return files, nil
}

// Write renders the blueprints and writes them under dir. Blueprints of
// programs or copybooks that no longer exist are left for the caller to
// remove.
func (s *System) Write(dir, title string) error {
	files, err := s.Render(dir, title)
	if err != nil {
		return err
	}
	for name, data := range files {
		path := filepath.Join(dir, name)
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(path, data, 0o644); err != nil {
			return err
		}
	}
	return nil
}

func renderBoth[T any](files map[string][]byte, dir, sub, name string, blueprint T, markdown func(string, T) string) error {
	data, err := json.MarshalIndent(blueprint, "", "  ")
	if err != nil {
		return err
	}
	files[filepath.Join(sub, name+".json")] = append(data, '\n')
	files[filepath.Join(sub, name+".md")] = []byte(withContents(markdown(filepath.Join(dir, sub), blueprint)))
	return nil
}

func (s *System) indexMarkdown(dir, title string) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# Blueprints: %s\n\nGenerated by Survey from the source, read as %s COBOL. Do not edit: regenerate.\n\n", title, s.Dialect.Title)
	b.WriteString("## Programs\n\n| Program | Kind | Source | Files | Paragraphs | Decision tables |\n| --- | --- | --- | --: | --: | --: |\n")
	for _, p := range s.Programs {
		tables := "0"
		if n := len(p.Rules.Tables); n > 0 {
			tables = fmt.Sprintf("[%d](rules/%s.md)", n, p.Name)
		}
		b.WriteString(row(fmt.Sprintf("[%s](programs/%s.md)", p.Name, p.Name), p.Kind, sourceLink(dir, p.Source, false),
			strconv.Itoa(len(p.Files)), strconv.Itoa(len(p.Paragraphs)), tables))
	}
	b.WriteString("\n## Copybooks\n\n| Copybook | Records | Used by |\n| --- | --- | --- |\n")
	for _, c := range s.Copybooks {
		var records []string
		for _, r := range c.Records {
			records = append(records, fmt.Sprintf("%s (%d bytes)", r.Name, r.Length))
		}
		if len(c.Paragraphs) > 0 {
			records = append(records, "procedure: "+strings.Join(c.Paragraphs, ", "))
		}
		b.WriteString(row(fmt.Sprintf("[%s](copybooks/%s.md)", c.Name, c.Name), strings.Join(records, ", "),
			programLinks(c.UsedBy, "programs/")))
	}
	if len(s.Jobs) > 0 {
		b.WriteString("\n## Jobs\n\n| Job | Source | Steps | Findings |\n| --- | --- | --: | --: |\n")
		for _, job := range s.Jobs {
			b.WriteString(row(fmt.Sprintf("[%s](jobs/%s.md)", job.Name, job.Name), sourceLink(dir, job.Source, false),
				strconv.Itoa(len(job.Steps)), strconv.Itoa(len(job.Findings))))
		}
	}
	writeDatasets(&b, s.Datasets)
	return b.String()
}

func (s *System) programMarkdown(dir string, p Program) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# %s\n\n", p.Name)
	writeDescription(&b, p.Description)
	fmt.Fprintf(&b, "Program %s: %d files, %d paragraphs.", sourceLink(dir, p.Source, false), len(p.Files), len(p.Paragraphs))
	if p.Within != "" {
		fmt.Fprintf(&b, " Nested in [%s](%s.md), which alone can call it.", p.Within, p.Within)
	}
	if n := len(p.Rules.Tables); n > 0 {
		fmt.Fprintf(&b, " Its business rules: [%d decision tables](../rules/%s.md).", n, p.Name)
	}
	b.WriteString("\n")
	if len(p.Identification) > 0 {
		b.WriteString("\n")
		for _, e := range p.Identification {
			fmt.Fprintf(&b, "- %s: %s\n", e.Paragraph, e.Text)
		}
	}

	b.WriteString("\n## Files\n\n| File | Kind | Assigned to | Organization | Status field | Opened | Records |\n| --- | --- | --- | --- | --- | --- | --- |\n")
	for _, f := range p.Files {
		organization := f.Organization
		if f.RecordKey != "" {
			organization += ", key " + f.RecordKey
		}
		if f.RelativeKey != "" {
			organization += ", record number in " + f.RelativeKey
		}
		if f.LengthIn != "" {
			organization += fmt.Sprintf(", records of %d to %d characters, length in %s", f.MinLength, f.MaxLength, f.LengthIn)
		}
		if f.Access != "" {
			organization += ", " + f.Access + " access"
		}
		b.WriteString(row(f.Name, f.Kind, f.Assign, organization, f.Status, strings.Join(f.Opened, ", "), strings.Join(f.Records, ", ")))
	}

	if len(p.Constants) > 0 {
		b.WriteString("\n## Constants\n\n| Constant | Value | Source |\n| --- | --- | --- |\n")
		for _, c := range p.Constants {
			b.WriteString(row(c.Name, c.Value, sourceLink(dir, c.Source, true)))
		}
	}

	fmt.Fprintf(&b, "\n## Flow\n\n![The paragraphs of %s and how control moves between them](%s.svg)\n", p.Name, p.Name)

	b.WriteString("\n## Paragraphs\n\n| Paragraph | Description | Source | Performs | Goes to | Performed by | Reached by |\n" +
		"| --- | --- | --- | --- | --- | --- | --- |\n")
	for _, para := range p.Paragraphs {
		b.WriteString(row(para.Name, para.Description, sourceLink(dir, para.Source, true),
			strings.Join(performTargets(para.Performs), ", "), strings.Join(goesTo(para), ", "),
			strings.Join(para.PerformedBy, ", "), strings.Join(para.ReachedBy, ", ")))
	}

	writeAnnotations(&b, s, p)
	writeDeclaratives(&b, dir, p)
	writeCalls(&b, dir, p)
	writeDataFlow(&b, dir, p)
	writeOrigins(&b, p)
	writeRelations(&b, dir, p)

	b.WriteString("\n## Records\n")
	for _, r := range p.Records {
		fmt.Fprintf(&b, "\n### %s\n\n", r.Name)
		where := "Working storage"
		switch {
		case r.File != "":
			where = "File " + r.File
		case r.Section == "linkage":
			where = "Linkage"
		}
		if r.Copybook != "" {
			fmt.Fprintf(&b, "%s. %d bytes, layout in copybook [%s](../copybooks/%s.md).%s\n", where, r.Length, r.Copybook, r.Copybook, typesSentence(r))
			continue
		}
		fmt.Fprintf(&b, "%s. %d bytes.%s%s\n\n", where, r.Length, sentence(r.Description), typesSentence(r))
		writeLayout(&b, dir, r.Field)
	}
	return b.String()
}

func copybookMarkdown(dir string, c Copybook) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# %s\n\n", c.Name)
	writeDescription(&b, c.Description)
	fmt.Fprintf(&b, "Copybook %s, used by %s.\n", sourceLink(dir, c.Source, false), programLinks(c.UsedBy, "../programs/"))
	if len(c.Paragraphs) > 0 {
		fmt.Fprintf(&b, "\nA copybook of procedure: its paragraphs, %s, are copied into the procedure division of each program that uses it, and are in each program's blueprint.\n", strings.Join(c.Paragraphs, ", "))
	}
	for _, r := range c.Records {
		fmt.Fprintf(&b, "\n## %s\n\n%d bytes.%s\n\n", r.Name, r.Length, sentence(r.Description))
		writeLayout(&b, dir, r.Field)
	}
	return b.String()
}

// writeDeclaratives writes the sections a program's runtime runs when an
// input or output statement fails.
func writeDeclaratives(b *strings.Builder, dir string, p Program) {
	if len(p.Declaratives) == 0 {
		return
	}
	b.WriteString("\n## Declaratives\n\nSections the runtime runs when an input or output statement fails, after which control goes on after the statement.\n\n" +
		"| Section | Runs on a failure of | Source |\n| --- | --- | --- |\n")
	for _, d := range p.Declaratives {
		on := slices.Clone(d.Files)
		for _, mode := range d.Modes {
			on = append(on, "any file opened "+mode)
		}
		b.WriteString(row(d.Section, strings.Join(on, ", "), sourceLink(dir, d.Source, true)))
	}
}

// writeLayout writes a record's fields as a table, one row per field and
// condition name, in source order.
func writeLayout(b *strings.Builder, dir string, record Field) {
	b.WriteString("| Level | Field | Kind | Start | Length | Picture | Usage | Notes | Source |\n| --: | --- | --- | --: | --: | --- | --- | --- | --- |\n")
	for _, r := range LayoutRows(record) {
		if r.Field == nil {
			b.WriteString(row("88", r.Prefix+r.Name, "", "", "", "", "", "VALUE "+strings.Join(r.Values, ", "), sourceLink(dir, r.Source, true)))
			continue
		}
		f := r.Field
		usage := f.Usage
		if usage == "DISPLAY" {
			usage = ""
		}
		b.WriteString(row(fmt.Sprintf("%02d", f.Level), r.Prefix+f.Name, f.Kind, strconv.Itoa(f.Start), strconv.Itoa(f.Length),
			f.Picture, usage, fieldNotes(*f), sourceLink(dir, f.Source, true)))
	}
}

// row writes one table row; an empty cell is a single space.
// row writes a Markdown table row. A | in a cell, as in a COBOL literal,
// is escaped, even inside code: tables split cells on it everywhere.
func row(cells ...string) string {
	var b strings.Builder
	for _, cell := range cells {
		if cell == "" {
			b.WriteString("| ")
		} else {
			b.WriteString("| " + strings.ReplaceAll(cell, "|", `\|`) + " ")
		}
	}
	b.WriteString("|\n")
	return b.String()
}

// writeDescription writes a header comment as preformatted text, keeping
// the line breaks and alignment its author chose.
func writeDescription(b *strings.Builder, description []string) {
	if len(description) == 0 {
		return
	}
	b.WriteString("```text\n")
	for _, line := range description {
		b.WriteString(line + "\n")
	}
	b.WriteString("```\n\n")
}

// sentence returns a description as a sentence to follow another, or nothing.
func sentence(description string) string {
	if description == "" {
		return ""
	}
	return " " + description
}

// FieldNotes describes what a field's layout entry says besides its
// picture: its description, what it redefines and what redefines it, how
// it repeats and what indexes it.
func FieldNotes(f Field) string { return fieldNotes(f) }

func fieldNotes(f Field) string {
	var notes []string
	if f.Description != "" && f.Level != 1 {
		notes = append(notes, f.Description)
	}
	if f.Redefines != "" {
		notes = append(notes, "REDEFINES "+f.Redefines)
	}
	if len(f.RedefinedBy) > 0 {
		notes = append(notes, "redefined by "+strings.Join(f.RedefinedBy, ", "))
	}
	switch {
	case f.DependingOn != "":
		notes = append(notes, fmt.Sprintf("OCCURS %d TO %d DEPENDING ON %s", f.OccursMin, f.Occurs, f.DependingOn))
	case f.Occurs > 0:
		notes = append(notes, fmt.Sprintf("OCCURS %d", f.Occurs))
	}
	if len(f.IndexedBy) > 0 {
		notes = append(notes, "INDEXED BY "+strings.Join(f.IndexedBy, ", "))
	}
	if f.Sign != "" {
		notes = append(notes, "SIGN "+f.Sign)
	}
	if len(f.Values) > 0 {
		notes = append(notes, "VALUE "+strings.Join(f.Values, ", "))
	}
	return strings.Join(notes, "; ")
}

// performTargets lists the procedures performed, each once, in order, and
// marks those a SORT performs.
func performTargets(performs []Perform) []string {
	var targets []string
	for _, p := range performs {
		target := p.Target
		if p.Thru != "" {
			target += " THRU " + p.Thru
		}
		if p.Sort {
			target += " (SORT)"
		}
		if !slices.Contains(targets, target) {
			targets = append(targets, target)
		}
	}
	return targets
}

// writeDataFlow writes what each paragraph reads and writes, and the
// lineage of each data item: where its values come from, by item.
func writeDataFlow(b *strings.Builder, dir string, p Program) {
	b.WriteString("\n## Data flow\n\n| Paragraph | Reads | Writes |\n| --- | --- | --- |\n")
	for _, para := range p.Paragraphs {
		b.WriteString(row(para.Name, strings.Join(para.Reads, ", "), strings.Join(para.Writes, ", ")))
	}
	if len(p.Lineage) == 0 {
		return
	}
	b.WriteString("\n## Lineage\n\nWhere each data item's values come from, grouped by the record they go into. " +
		"A data item links to the record it belongs to.\n")
	records := recordsByItem(p)
	for _, g := range groupLineage(p, records) {
		fmt.Fprintf(b, "\n### %s\n\n%s| Into | From | Statement | Paragraph | Source |\n| --- | --- | --- | --- | --- |\n", g.title, g.intro)
		for _, e := range g.edges {
			b.WriteString(row(e.ToText(), lineageItem(e, records), e.Verb, e.Paragraph, sourceLink(dir, e.Source, true)))
		}
	}
}

// lineageGroup is the lineage into one record, into files, or into data
// items the program does not declare.
type lineageGroup struct {
	title, intro string
	edges        []Lineage
}

// groupLineage groups a program's lineage by what it goes into: each
// record in the order the program declares them, then files, then other
// data items. Within a group, the lineage is ordered by the item written.
func groupLineage(p Program, records map[string]Record) []lineageGroup {
	groups := make([]lineageGroup, len(p.Records)+2)
	files, other := len(p.Records), len(p.Records)+1
	groups[files] = lineageGroup{title: "Out of the program",
		intro: "Records written to files, items passed to the programs called, and items displayed to the job's output.\n\n"}
	groups[other] = lineageGroup{title: "Into other data items",
		intro: "Data items the program does not declare, such as special registers and index names.\n\n"}
	for i, r := range p.Records {
		intro := "Record [" + r.Name + "](#" + HeadingAnchor(r.Name) + ")"
		if r.Copybook != "" {
			intro += ", from copybook " + copybookLink(r.Copybook)
		}
		groups[i] = lineageGroup{title: "Into " + r.Name, intro: intro + ".\n\n"}
	}
	for _, e := range p.Lineage {
		i := other
		if r, ok := records[e.To]; !e.ToItem() {
			i = files
		} else if ok {
			i = slices.IndexFunc(p.Records, func(pr Record) bool { return pr.Name == r.Name })
		}
		groups[i].edges = append(groups[i].edges, e)
	}
	var nonEmpty []lineageGroup
	for _, g := range groups {
		if len(g.edges) > 0 {
			slices.SortStableFunc(g.edges, func(x, y Lineage) int { return strings.Compare(x.To, y.To) })
			nonEmpty = append(nonEmpty, g)
		}
	}
	return nonEmpty
}

// lineageItem writes where a value comes from: a file, or a data item
// linked to the record it belongs to, with the record's name on hover when
// the item is a field of it.
func lineageItem(e Lineage, records map[string]Record) string {
	name := e.From
	if !e.FromItem() {
		return e.FromText()
	}
	r, ok := records[name]
	switch {
	case ok && r.Name == name:
		return fmt.Sprintf("[%s](#%s)", name, HeadingAnchor(r.Name))
	case ok:
		return fmt.Sprintf("[%s](#%s \"in %s\")", name, HeadingAnchor(r.Name), r.Name)
	}
	return name
}

// recordsByItem maps every data item the program declares to the record it
// belongs to.
func recordsByItem(p Program) map[string]Record {
	records := map[string]Record{}
	var walk func(r Record, f Field)
	walk = func(r Record, f Field) {
		records[f.Name] = r
		for _, child := range f.Fields {
			walk(r, child)
		}
	}
	for _, r := range p.Records {
		walk(r, r.Field)
	}
	return records
}

// goesTo lists where a paragraph goes other than by PERFORM: its GO TO
// targets, each once, and the paragraph it falls into.
func goesTo(para Paragraph) []string {
	var targets []string
	for _, g := range para.GoTos {
		if !slices.Contains(targets, g.Target) {
			targets = append(targets, g.Target)
		}
	}
	if para.FallsInto != "" {
		targets = append(targets, para.FallsInto+" (falls into)")
	}
	return targets
}

func programLinks(names []string, prefix string) string {
	if len(names) == 0 {
		return "no program"
	}
	var links []string
	for _, name := range names {
		links = append(links, fmt.Sprintf("[%s](%s%s.md)", name, prefix, name))
	}
	return strings.Join(links, ", ")
}

// sourceLink links a source reference, "path" or "path:line", relative to
// the directory of the blueprint that contains it. With line set, the text
// is the file name and line; otherwise the file name.
func sourceLink(dir, source string, line bool) string {
	path, lineNo, hasLine := strings.Cut(source, ":")
	text := filepath.Base(path)
	if hasLine && line {
		text += ":" + lineNo
	}
	return fmt.Sprintf("[%s](%s)", text, sourceTarget(dir, source))
}

// sourceTarget is the relative URL of a source reference, with the line as
// a fragment.
func sourceTarget(dir, source string) string {
	path, lineNo, hasLine := strings.Cut(source, ":")
	target, err := filepath.Rel(dir, path)
	if err != nil {
		target = path
	}
	target = filepath.ToSlash(target)
	if hasLine {
		target += "#L" + lineNo
	}
	return target
}
